// 5. Message Handler
// ---------------------------------------------------------------------------

self.onmessage = async (event) => {
  const { type, id, payload } = event.data;

  try {
    // ── Phishing Analysis ────────────────────────────────────────────────────
    if (type === 'ANALYZE') {
      if (!payload?.text || typeof payload.text !== 'string') {
        postMessage({ type: 'ERROR', id, payload: 'ANALYZE: missing or invalid text' });
        return;
      }
      const results = await analyzePageText(payload.text);
      postMessage({ type: 'RESULT', id, payload: results });
      return;
    }

    // ── Consent / Dark Pattern Analysis ─────────────────────────────────────
    if (type === 'CONSENT_ANALYZE') {
      const { consentText, anchors } = payload || {};
      if (!consentText || !Array.isArray(anchors) || anchors.length === 0) {
        postMessage({ type: 'RESULT', id, payload: [] });
        return;
      }
      const findings = await analyzeConsentText(consentText, anchors);
      postMessage({ type: 'RESULT', id, payload: findings });
      return;
    }

    // ── Raw Embedding (for custom callers) ───────────────────────────────────
    if (type === 'EMBED') {
      if (!payload?.text) {
        postMessage({ type: 'ERROR', id, payload: 'EMBED: missing text' });
        return;
      }
      const embedding = await computeEmbedding(payload.text);
      postMessage({ type: 'RESULT', id, payload: Array.from(embedding) });
      return;
    }

    // ── Health Check ─────────────────────────────────────────────────────────
    if (type === 'PING') {
      await getEmbeddingPipeline();
      postMessage({ type: 'PONG', id });
      return;
    }

    // ── Restore Cached Anchor Embeddings ─────────────────────────────────────
    // Sent by offscreen.js on worker startup with embeddings from session storage.
    // Avoids re-running all anchor inference after a service worker restart.
    if (type === 'RESTORE_ANCHORS') {
      if (payload && typeof payload === 'object') {
        let restored = 0;
        for (const [key, floatArray] of Object.entries(payload)) {
          if (BRAND_ANCHORS[key] && Array.isArray(floatArray) && floatArray.length === 384) {
            BRAND_ANCHORS[key].embedding = new Float32Array(floatArray);
            restored++;
          }
        }
        // Only mark as fully computed if ALL anchors were restored
        const totalAnchors = Object.keys(BRAND_ANCHORS).length;
        if (restored === totalAnchors) {
          _anchorsComputed = true;
          console.log(`[GhostForm ML] All ${restored} anchor embeddings restored from session cache.`);
        } else {
          console.log(`[GhostForm ML] Partially restored: ${restored}/${totalAnchors} anchors.`);
          // Remaining nulls will be computed lazily on first ANALYZE call
        }
      }
      postMessage({ type: 'RESULT', id, payload: 'anchors_restored' });
      return;
    }

    // ── Unknown message type ─────────────────────────────────────────────────
    console.warn('[GhostForm ML] Unknown message type:', type);
    postMessage({ type: 'ERROR', id, payload: `Unknown type: ${type}` });

  } catch (error) {
    console.error('[GhostForm ML] Handler error:', error);
    postMessage({ type: 'ERROR', id, payload: error.message });
  }
};

