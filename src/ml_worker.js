// ---------------------------------------------------------------------------
// 4. Core Inference Functions
// ---------------------------------------------------------------------------

/**
 * Generates a 384-dimensional embedding for the provided text.
 * Uses mean pooling + L2 normalization (the standard for all-MiniLM-L6-v2).
 *
 * @param {string} text
 * @returns {Promise<Float32Array>} Normalized embedding vector.
 */
async function computeEmbedding(text) {
  const pipe = await getEmbeddingPipeline();
  const output = await pipe(text, {
    pooling:   'mean',
    normalize: true,
  });
  return output.data; // Float32Array, shape [384]
}

/**
 * Ensures all brand anchor embeddings are computed.
 * On first call: runs inference for each anchor (~15 anchors × ~10ms each).
 * On subsequent calls: returns immediately (embeddings are cached in memory).
 * After computation: sends STORE_ANCHORS to offscreen.js for session persistence.
 */
let _anchorsComputed = false;

async function ensureAnchorsReady() {
  if (_anchorsComputed) return;

  // Check if any anchor still needs embedding
  const missing = Object.entries(BRAND_ANCHORS).filter(([, a]) => !a.embedding);
  if (missing.length === 0) {
    _anchorsComputed = true;
    return;
  }

  console.log(`[GhostForm ML] Computing ${missing.length} brand anchor embeddings...`);
  const startMs = Date.now();

  for (const [key, anchor] of missing) {
    anchor.embedding = await computeEmbedding(anchor.anchorText);
  }

  const elapsed = Date.now() - startMs;
  console.log(`[GhostForm ML] Anchor embeddings ready in ${elapsed}ms.`);
  _anchorsComputed = true;

  // Persist anchors to session storage via offscreen.js so they survive
  // service worker restarts without re-computation.
  const serializable = {};
  for (const [key, anchor] of Object.entries(BRAND_ANCHORS)) {
    serializable[key] = Array.from(anchor.embedding);
  }
  postMessage({ type: 'STORE_ANCHORS', payload: serializable });
}

/**
 * Main phishing analysis: embeds the page text, computes cosine similarity
 * against all brand anchors, and returns sorted results.
 *
 * @param {string} pageText - Sanitized visible text from the web page (≤ 2000 chars).
 * @returns {Promise<Array<{brand, label, score}>>} Sorted by score descending.
 */
async function analyzePageText(pageText) {
  await ensureAnchorsReady();

  const pageEmbedding = await computeEmbedding(pageText);

  const results = Object.entries(BRAND_ANCHORS).map(([key, anchor]) => ({
    brand: key,
    label: anchor.label,
    score: parseFloat(cos_sim(pageEmbedding, anchor.embedding).toFixed(4)),
  }));

  results.sort((a, b) => b.score - a.score);
  return results;
}

/**
 * Consent analysis for Fine-Print AI:
 * Embeds each anchor phrase in `anchors[]` and computes similarity against
 * the extracted consent text. Returns indices + scores for matches.
 *
 * @param {string}   consentText
 * @param {string[]} anchors     — dark pattern canonical phrases
 * @returns {Promise<Array<{index, score}>>}
 */
async function analyzeConsentText(consentText, anchors) {
  const consentEmbed = await computeEmbedding(consentText);
  const findings = [];

  for (let i = 0; i < anchors.length; i++) {
    const anchorEmbed = await computeEmbedding(anchors[i]);
    const score = parseFloat(cos_sim(consentEmbed, anchorEmbed).toFixed(4));
    findings.push({ index: i, score });
  }

  return findings;
}

// ---------------------------------------------------------------------------
// 5. Message Handler
// ---------------------------------------------------------------------------

self.onmessage = async (event) => {
  const { type, id, payload } = event.data;

  try {
    // ── Phishing Analysis ────────────────────────────────────────────────────
    if (type === 'ANALYZE') {
      if (!payload?.text || typeof payload.text !== 'string') {
        postMessage({ type: 'ERROR', id, payload: 'ANALYZE: missing or invalid text' });
        return;
      }
      const results = await analyzePageText(payload.text);
      postMessage({ type: 'RESULT', id, payload: results });
      return;
    }

    // ── Consent / Dark Pattern Analysis ─────────────────────────────────────
    if (type === 'CONSENT_ANALYZE') {
      const { consentText, anchors } = payload || {};
      if (!consentText || !Array.isArray(anchors) || anchors.length === 0) {
        postMessage({ type: 'RESULT', id, payload: [] });
        return;
      }
      const findings = await analyzeConsentText(consentText, anchors);
      postMessage({ type: 'RESULT', id, payload: findings });
      return;
    }

    // ── Raw Embedding (for custom callers) ───────────────────────────────────
    if (type === 'EMBED') {
      if (!payload?.text) {
        postMessage({ type: 'ERROR', id, payload: 'EMBED: missing text' });
        return;
      }
      const embedding = await computeEmbedding(payload.text);
      postMessage({ type: 'RESULT', id, payload: Array.from(embedding) });
      return;
    }

    // ── Health Check ─────────────────────────────────────────────────────────
    if (type === 'PING') {
      await getEmbeddingPipeline();
      postMessage({ type: 'PONG', id });
      return;
    }

    // ── Restore Cached Anchor Embeddings ─────────────────────────────────────
    // Sent by offscreen.js on worker startup with embeddings from session storage.
    // Avoids re-running all anchor inference after a service worker restart.
    if (type === 'RESTORE_ANCHORS') {
      if (payload && typeof payload === 'object') {
        let restored = 0;
        for (const [key, floatArray] of Object.entries(payload)) {
          if (BRAND_ANCHORS[key] && Array.isArray(floatArray) && floatArray.length === 384) {
            BRAND_ANCHORS[key].embedding = new Float32Array(floatArray);
            restored++;
          }
        }
        // Only mark as fully computed if ALL anchors were restored
        const totalAnchors = Object.keys(BRAND_ANCHORS).length;
        if (restored === totalAnchors) {
          _anchorsComputed = true;
          console.log(`[GhostForm ML] All ${restored} anchor embeddings restored from session cache.`);
        } else {
          console.log(`[GhostForm ML] Partially restored: ${restored}/${totalAnchors} anchors.`);
          // Remaining nulls will be computed lazily on first ANALYZE call
        }
      }
      postMessage({ type: 'RESULT', id, payload: 'anchors_restored' });
      return;
    }

    // ── Unknown message type ─────────────────────────────────────────────────
    console.warn('[GhostForm ML] Unknown message type:', type);
    postMessage({ type: 'ERROR', id, payload: `Unknown type: ${type}` });

  } catch (error) {
    console.error('[GhostForm ML] Handler error:', error);
    postMessage({ type: 'ERROR', id, payload: error.message });
  }
};

// ---------------------------------------------------------------------------
// 6. Pre-warm on Worker Startup
// ---------------------------------------------------------------------------
// Load the ONNX model immediately when the worker spawns.  This ensures the
// first real ANALYZE request returns quickly (model already in memory).
// After pre-warm (success or failure), post READY so offscreen.js knows it's
// safe to send RESTORE_ANCHORS without a race condition.

getEmbeddingPipeline()
  .then(() => {
    postMessage({ type: 'READY', payload: 'pipeline_warm' });
  })
  .catch((err) => {
    console.warn('[GhostForm ML] Pre-warm failed, will retry on first request:', err.message);
    postMessage({ type: 'READY', payload: 'pipeline_cold' });
  });
