/**
 * ml_worker.js — Ghost Form Phase 3 (Production Ready)
 *
 * Runs inside a dedicated Web Worker hosted by the Offscreen Document.
 * This execution context survives MV3 service worker suspensions.
 *
 * Responsibilities:
 *  1. Initialize the Transformers.js feature-extraction pipeline once (singleton).
 *  2. Cache the ONNX model via the Cache API so it survives worker restarts.
 *  3. Generate 384-dim L2-normalized sentence embeddings via mean pooling.
 *  4. Compute cosine similarity against pre-computed brand anchor vectors.
 *  5. Handle CONSENT_ANALYZE for Fine-Print AI dark pattern detection.
 *  6. Post results back to offscreen.js via postMessage.
 *
 * Message Protocol:
 *   IN  { type: 'ANALYZE',         id, payload: { text } }         → phishing check
 *   IN  { type: 'CONSENT_ANALYZE', id, payload: { consentText, anchors: string[] } }
 *   IN  { type: 'PING',            id }                            → health check
 *   IN  { type: 'RESTORE_ANCHORS', id, payload: { key: float[] } } → reload from cache
 *   OUT { type: 'RESULT',  id, payload }
 *   OUT { type: 'ERROR',   id, payload: string }
 *   OUT { type: 'READY',   payload: 'pipeline_warm'|'pipeline_cold' }
 *   OUT { type: 'STATUS',  payload: 'loading_model'|'model_ready' }
 *   OUT { type: 'STORE_ANCHORS', payload: { key: float[] } }
 */

import { pipeline, env, cos_sim } from '@xenova/transformers';

// ---------------------------------------------------------------------------
// 1. Configure Transformers.js for the Chrome Extension environment
// ---------------------------------------------------------------------------

// Use the browser's Cache API to persist the ONNX model across worker restarts.
// Without this, the ~23MB model would be re-downloaded from HuggingFace on
// every service worker wake-up.
env.useBrowserCache  = true;
env.allowLocalModels = false;

// Point the WASM resolver to the extension's dist/ folder.
// The WASM files are copied there by the Vite build.
env.backends.onnx.wasm.wasmPaths = chrome.runtime.getURL('dist/');

// ---------------------------------------------------------------------------
// 2. Singleton Pipeline
// ---------------------------------------------------------------------------

const MODEL_ID = 'Xenova/all-MiniLM-L6-v2';
let   embeddingPipeline = null;

/**
 * Lazily initializes the pipeline on first use.
 * Subsequent calls return the cached instance in O(1).
 * Reports STATUS messages so the offscreen doc can log download progress.
 *
 * @returns {Promise<FeatureExtractionPipeline>}
 */
async function getEmbeddingPipeline() {
  if (embeddingPipeline) return embeddingPipeline;

  postMessage({ type: 'STATUS', payload: 'loading_model' });

  try {
    embeddingPipeline = await pipeline('feature-extraction', MODEL_ID, {
      quantized: true, // INT8 quantized — ~23MB vs ~90MB fp32
      progress_callback: (progress) => {
        postMessage({ type: 'MODEL_PROGRESS', payload: progress });
      },
    });

    postMessage({ type: 'STATUS', payload: 'model_ready' });
    return embeddingPipeline;

  } catch (error) {
    postMessage({ type: 'ERROR', payload: `Model load failed: ${error.message}` });
    throw error;
  }
}

